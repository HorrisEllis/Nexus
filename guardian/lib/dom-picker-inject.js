/**
 * guardian/lib/dom-picker-inject.js
 * UUID: nexus-guardian-dom-picker-v1-0000-4000-0000-000000000001
 * Version: 1.0.0
 *
 * This is NOT a Node module — it is a string of browser JS that Guardian
 * sends to the userscript via NCP (NEXUS_DOM_PICK message).
 * The userscript eval()s it in the page context to activate the picker overlay.
 *
 * DESIGN:
 *   - Injects a full-page overlay with a crosshair cursor.
 *   - Highlights the element under the cursor with a blue outline.
 *   - On click: computes a stable CSS selector, posts NEXUS_DOM_PICK_RESULT
 *     back to Guardian via fetch(), removes the overlay.
 *   - ESC cancels — posts NEXUS_DOM_PICK_CANCEL.
 *   - Timeout (30s) auto-cancels.
 *
 * Selector algorithm (stable → specific):
 *   1. data-testid, aria-label, name, role attributes
 *   2. id (if not autogenerated: no uuid/hash chars, <30 chars)
 *   3. tagName + nth-of-type within parent
 *   4. Full path up to body, max depth 5
 *
 * The function exported here returns the JS string to inject.
 * It is parameterised with { jobName, commandName, guardianUrl }.
 */

'use strict';

function buildPickerScript({ commandName, provider, guardianUrl = 'http://127.0.0.1:7820' }) {
  return `
(function() {
'use strict';

// Guard: don't double-inject
if (document.getElementById('nexus-dom-picker-overlay')) return;

const COMMAND  = ${JSON.stringify(commandName)};
const PROVIDER = ${JSON.stringify(provider)};
const GU_URL   = ${JSON.stringify(guardianUrl)};
const TIMEOUT_MS = 30000;

// ── Stable CSS selector ───────────────────────────────────────────────────────
function stableSelector(el) {
  if (!el || el === document.body) return 'body';

  // Priority 1: semantic attributes
  for (const attr of ['data-testid', 'data-cy', 'name', 'aria-label', 'placeholder']) {
    const v = el.getAttribute?.(attr);
    if (v && v.length < 60 && !/[{}\\[\\]]/.test(v)) {
      const sel = el.tagName.toLowerCase() + '[' + attr + '=' + JSON.stringify(v) + ']';
      if (document.querySelectorAll(sel).length === 1) return sel;
    }
  }

  // Priority 2: id (not autogenerated)
  if (el.id && el.id.length < 30 && !/[0-9a-f]{8,}/i.test(el.id)) {
    return '#' + CSS.escape(el.id);
  }

  // Priority 3: class combination (first 2 stable-looking classes)
  const classes = Array.from(el.classList || [])
    .filter(c => c.length > 3 && c.length < 40 && !/^[0-9]/.test(c) && !/[A-Z0-9]{6,}/.test(c))
    .slice(0, 2);
  if (classes.length > 0) {
    const sel = el.tagName.toLowerCase() + '.' + classes.join('.');
    try { if (document.querySelectorAll(sel).length <= 3) return sel; } catch(_) {}
  }

  // Priority 4: nth-of-type path (max depth 5)
  const parts = [];
  let node = el;
  for (let d = 0; d < 5 && node && node !== document.body; d++) {
    const tag = node.tagName.toLowerCase();
    const parent = node.parentElement;
    if (!parent) break;
    const siblings = Array.from(parent.children).filter(c => c.tagName === node.tagName);
    const idx = siblings.indexOf(node) + 1;
    parts.unshift(idx > 1 ? tag + ':nth-of-type(' + idx + ')' : tag);
    node = parent;
  }
  return parts.join(' > ') || el.tagName.toLowerCase();
}

// ── Overlay ───────────────────────────────────────────────────────────────────
const overlay = document.createElement('div');
overlay.id = 'nexus-dom-picker-overlay';
Object.assign(overlay.style, {
  position:  'fixed', inset: '0', zIndex: '2147483647',
  cursor:    'crosshair', background: 'rgba(0,30,60,0.18)',
  transition: 'background .15s',
});

// ── Banner ────────────────────────────────────────────────────────────────────
const banner = document.createElement('div');
Object.assign(banner.style, {
  position: 'fixed', top: '0', left: '0', right: '0',
  background: '#05080f', borderBottom: '2px solid #00d4ff',
  color: '#00d4ff', fontFamily: 'monospace', fontSize: '13px',
  padding: '8px 16px', zIndex: '2147483647',
  display: 'flex', alignItems: 'center', gap: '12px',
  userSelect: 'none',
});
banner.innerHTML =
  '<span>⬡ NEXUS › DOM PICKER</span>' +
  '<span style="color:#666;font-size:11px">Mapping command: <strong style="color:#00d4ff">' + COMMAND + '</strong></span>' +
  '<span style="color:#666;font-size:11px;margin-left:auto">Click an element · ESC to cancel</span>';

// ── Highlight box ─────────────────────────────────────────────────────────────
const highlight = document.createElement('div');
highlight.id = 'nexus-picker-highlight';
Object.assign(highlight.style, {
  position:      'fixed', zIndex: '2147483646', pointerEvents: 'none',
  border:        '2px solid #00d4ff',
  boxShadow:     '0 0 0 1px rgba(0,212,255,0.3), inset 0 0 0 1px rgba(0,212,255,0.1)',
  background:    'rgba(0,212,255,0.05)',
  borderRadius:  '2px', transition: 'all .08s',
  display:       'none',
});

// ── Selector label ────────────────────────────────────────────────────────────
const selLabel = document.createElement('div');
Object.assign(selLabel.style, {
  position: 'fixed', bottom: '12px', left: '12px', right: '12px',
  background: '#05080f', border: '1px solid #00d4ff', color: '#00d4ff',
  fontFamily: 'monospace', fontSize: '11px', padding: '6px 10px',
  zIndex: '2147483647', borderRadius: '2px', userSelect: 'none',
  display: 'none', wordBreak: 'break-all',
});

document.body.appendChild(overlay);
document.body.appendChild(banner);
document.body.appendChild(highlight);
document.body.appendChild(selLabel);

// ── Hover tracking ────────────────────────────────────────────────────────────
let _hovered = null;

function _updateHighlight(el) {
  if (!el || el === overlay || el === banner || el === highlight || el === selLabel) return;
  _hovered = el;
  const r = el.getBoundingClientRect();
  Object.assign(highlight.style, {
    display: 'block',
    top:    (r.top   - 2) + 'px',
    left:   (r.left  - 2) + 'px',
    width:  (r.width + 4) + 'px',
    height: (r.height + 4) + 'px',
  });
  const sel = stableSelector(el);
  selLabel.style.display = 'block';
  selLabel.textContent   = sel + ' · ' + el.tagName.toLowerCase() + ' · ' + (el.innerText || '').slice(0, 60).replace(/\\n/g, ' ');
}

overlay.addEventListener('mousemove', e => {
  overlay.style.pointerEvents = 'none';
  const underneath = document.elementFromPoint(e.clientX, e.clientY);
  overlay.style.pointerEvents = '';
  if (underneath && underneath !== overlay) _updateHighlight(underneath);
});

// ── Pick on click ─────────────────────────────────────────────────────────────
overlay.addEventListener('click', e => {
  e.preventDefault(); e.stopPropagation();
  overlay.style.pointerEvents = 'none';
  const target = document.elementFromPoint(e.clientX, e.clientY);
  overlay.style.pointerEvents = '';
  if (!target || target === overlay || target === banner) return;

  const selector = stableSelector(target);
  const meta = {
    tagName:    target.tagName,
    id:         target.id || null,
    classes:    Array.from(target.classList).slice(0, 5),
    innerText:  (target.innerText || '').slice(0, 100),
    href:       target.href || null,
    type:       target.type || null,
    name:       target.getAttribute('name') || null,
  };

  _cleanup();

  console.log('[nexus-picker] picked:', selector, meta);

  // Post result back to Guardian
  fetch(GU_URL + '/cli/pick-result', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      commandName: COMMAND,
      provider:    PROVIDER,
      selector,
      meta,
      ts: Date.now(),
    }),
  }).catch(e => console.warn('[nexus-picker] post failed:', e.message));

}, { once: true });

// ── ESC cancel ────────────────────────────────────────────────────────────────
function _onKey(e) {
  if (e.key === 'Escape') {
    _cleanup();
    fetch(GU_URL + '/cli/pick-cancel', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ commandName: COMMAND, provider: PROVIDER, ts: Date.now() }),
    }).catch(() => {});
  }
}
document.addEventListener('keydown', _onKey);

// ── Timeout (30s) ─────────────────────────────────────────────────────────────
const _timeout = setTimeout(() => {
  _cleanup();
  fetch(GU_URL + '/cli/pick-cancel', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ commandName: COMMAND, provider: PROVIDER, reason: 'timeout', ts: Date.now() }),
  }).catch(() => {});
}, ${TIMEOUT_MS});

// ── Cleanup ───────────────────────────────────────────────────────────────────
function _cleanup() {
  clearTimeout(_timeout);
  document.removeEventListener('keydown', _onKey);
  overlay.remove(); banner.remove(); highlight.remove(); selLabel.remove();
}

})();
`;
}

module.exports = { buildPickerScript };
