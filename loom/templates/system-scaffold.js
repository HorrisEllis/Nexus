// ── Projection 10: capabilities.js — capability -> command routing, enforced ──
function _renderCapabilities(systemName, capabilities, operationIds) {
  const names = Object.keys(capabilities);
  for (const capName of names) {
    const routed = capabilities[capName];
    if (!Array.isArray(routed) || routed.length === 0) {
      throw new Error(`[scaffold] capability "${capName}" routes to 0 commands — |routes(C)| >= 1 is required, not optional`);
    }
    for (const opId of routed) {
      if (!operationIds.includes(opId)) {
        throw new Error(`[scaffold] capability "${capName}" routes to unknown operation id "${opId}"`);
      }
    }
  }
  const entries = names.map(capName =>
    `  { id: '${systemName}.${capName}.capability', routes: ${JSON.stringify(capabilities[capName].map(id => `${systemName}.${id}.command`))} },`
  ).join('\n');
  return `'use strict';
/**
 * ${systemName}/capabilities.js — generated by loom/templates/system-scaffold.js
 * Every capability node here was verified at scaffold time to route to
 * >=1 real command node (the capability_invariant from the 2026-09-11
 * compartment/nodetype phasemap). A capability with 0 routes fails
 * scaffoldSystem() outright, not silently.
 */
module.exports = [
${entries}
];
`;
}

