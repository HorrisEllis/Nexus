function _renderEventContract(systemName, tier, name) {
  return JSON.stringify({
    id: `${systemName}.${name}`,
    tier,
    version: '0.1.0',
    emits: [],
    handles: [],
  }, null, 2) + '\n';
}

function _scaffoldModulesAndComponents(sysDir, systemName, modules) {
  const written = [];
  for (const mod of modules || []) {
    const modDir = path.join(sysDir, 'modules', mod.name);
    fs.mkdirSync(modDir, { recursive: true });
    const modSpecPath = path.join(modDir, `${mod.name}.spec`);
    fs.writeFileSync(modSpecPath, _renderCompartmentSpec(systemName, 'module', mod.name, `${systemName}/modules/${mod.name}`));
    written.push(modSpecPath);
    const modContractPath = path.join(modDir, 'event-contract.json');
    fs.writeFileSync(modContractPath, _renderEventContract(systemName, 'module', mod.name));
    written.push(modContractPath);

    for (const comp of mod.components || []) {
      const compDir = path.join(modDir, 'components', comp.name);
      fs.mkdirSync(compDir, { recursive: true });
      const compSpecPath = path.join(compDir, `${comp.name}.spec`);
      fs.writeFileSync(compSpecPath, _renderCompartmentSpec(systemName, 'component', comp.name, `${systemName}/modules/${mod.name}/components/${comp.name}`));
      written.push(compSpecPath);
      const compContractPath = path.join(compDir, 'event-contract.json');
      fs.writeFileSync(compContractPath, _renderEventContract(systemName, 'component', comp.name));
      written.push(compContractPath);
    }
  }
  return written;
}

/**
 * -> { written: [...paths], registered: {component, hooks} }
 *
 * Writes all projections to disk under outDir/<name>/ (+ data/<name>/
 * sibling to outDir for failures/invariant), and registers the system as
 * a real LOOM component with one hook per operation, wired nowhere yet
 * (wiring is Phase 3's job, per the Lattice L3 note — a fresh system
 * starts with hooks, not wires, exactly like your real "164 hooks
 * replayed, 0 live wires" today).
 *
 * `modules` (optional): [{ name, components: [{ name }, ...] }, ...] —
 * each gets a logical-compartment skeleton (own dir, own living .spec,
 * own event-contract.json), never a spawned process — see locked_model
 * in the 2026-09-11 compartment/nodetype phasemap.
 *
 * `capabilities` (optional): { capName: [operationId, ...] } — each must
 * route to >=1 real operation id, checked before anything is written
 * (capability_invariant, |routes(C)| >= 1). A capability with 0 routes
 * throws, not warns.
 */
function scaffoldSystem(name, { port, purpose = '', operations, outDir, dataDir = null, modules = [], capabilities = {} } = {}) {
  if (!name || !/^[a-z][a-z0-9-]*$/.test(name)) {
    throw new Error('[scaffold] name must be lowercase, start with a letter, e.g. "my-system"');
  }
  if (!port) throw new Error('[scaffold] port is required');
  _validateOperations(operations);
  if (!outDir) throw new Error('[scaffold] outDir is required');

  // Fail before writing anything — capability_invariant is checked up
  // front, not after files are already on disk.
  const operationIds = operations.map(op => op.id);
  for (const [capName, routed] of Object.entries(capabilities)) {
    if (!Array.isArray(routed) || routed.length === 0) {
      throw new Error(`[scaffold] capability "${capName}" routes to 0 commands — |routes(C)| >= 1 is required`);
    }
    for (const opId of routed) {
      if (!operationIds.includes(opId)) {
        throw new Error(`[scaffold] capability "${capName}" routes to unknown operation id "${opId}"`);
      }
    }
  }

  const sysDir = path.join(outDir, name);
  const dirs = ['cli', 'api', 'docs', 'spec'];
  for (const d of dirs) fs.mkdirSync(path.join(sysDir, d), { recursive: true });

  // Own data directory, sibling to outDir — matches versionium/ollama's
  // real precedent (data/<system>/{failures,invariant}), not reusing
  // another system's shared tables. Distinct from `dataDir` below, which
  // is LoomDriver's OWN registry storage location — conflating the two
  // would put a system's failures/invariant folders inside Loom's
  // internal registry directory whenever a caller happened to pass one.
  const dataRoot = path.join(outDir, 'data', name);
  for (const sub of ['failures', 'invariant']) {
    fs.mkdirSync(path.join(dataRoot, sub), { recursive: true });
  }

  const written = [];
  function _write(rel, content) {
    const full = path.join(sysDir, rel);
    fs.writeFileSync(full, content);
    written.push(full);
  }

  // Projection 1 — real .spec (nexus-system-foundation shape), not .spec.md
  _write('spec/' + name + '.spec', _renderSpec(name, operations, port, purpose));

  // Projection 2 — CLI (first)
  _write('cli/index.js', _renderCli(name, operations));

  // Projection 3 — API (second)
  _write('api/index.js', _renderApi(name, operations, port));

  // Projection 4 — file maps + configs
  _write('registry-components.js', _renderRegistryComponents(name, operations));

  // Projection 5 — interaction contract
  _write('interaction-contract.json', JSON.stringify(_renderInteractionContract(name, operations, port), null, 2));

  // Projection 6 — config.js
  _write('config.js', _renderConfig(name, port));

  // Projection 7 — event-taxonomy.js (ET1 shape)
  _write('event-taxonomy.js', _renderEventTaxonomy(name, operations));

  // Projection 8 — tool-index.js / command-index.js
  _write('command-index.js', _renderCommandIndex(name, operations));
  _write('tool-index.js', _renderToolIndex(name));

  // Projection 9 — capabilities.js, only if any were declared
  if (Object.keys(capabilities).length > 0) {
    _write('capabilities.js', _renderCapabilities(name, capabilities, operationIds));
  }

  // Projection 10 — module/component logical-compartment skeletons
  written.push(..._scaffoldModulesAndComponents(sysDir, name, modules));

  // Register into LOOM's own component/seam/hook/wire registry — dogfooded,
  // same as Warp and LOOM's own agent-suite were.
  const driver = new LoomDriver({ dataDir });
  const compId = `nexus.${name}`;
  const compResult = driver.declare('component', {
    id: compId, namespace: name, name, version: '0.1.0',
    uuid: `nexus-${name}-v1-0000-2026-0702-jamesbrooks-scaffold`,
  });

  const hookResults = [];
  if (compResult.ok) {
    for (const op of operations) {
      const r = driver.declare('hook', {
        id: `${compId}.${op.id}`, component_id: compId, name: op.id,
        type: 'api', direction: 'out',
        uuid: `nexus-${name}-hook-${op.id}-v1-0000-2026-0702-jamesbrooks-scaffold`,
      });
      hookResults.push(r);
    }
  }

  return { written, registered: { component: compResult, hooks: hookResults } };
}

