/**
 * Operation shape (the one thing you define per system):
 *   { id, verb, method, apiPath, params: [], description }
 * `verb` -> CLI command (e.g. "list", "create"). `method`+`apiPath` -> API route.
 */
function _validateOperations(operations) {
  if (!Array.isArray(operations) || operations.length === 0) {
    throw new Error('[scaffold] operations must be a non-empty array');
  }
  for (const op of operations) {
    for (const key of ['id', 'verb', 'method', 'apiPath']) {
      if (!op[key]) throw new Error(`[scaffold] operation missing required key "${key}": ${JSON.stringify(op)}`);
    }
  }
}

