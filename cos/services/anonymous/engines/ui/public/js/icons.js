/** Build an <svg> string for a named glyph. */
function icon(name, size = 16) {
  const d = P[name];
  if (!d) return '';
  const paths = d.split(' M').map((seg, i) => (i === 0 ? seg : 'M' + seg))
    .map(seg => `<path d="${seg}"/>`).join('');
  return `<svg viewBox="0 0 24 24" width="${size}" height="${size}" fill="none" `
       + `stroke="currentColor" stroke-width="1.9" stroke-linecap="round" `
       + `stroke-linejoin="round" aria-hidden="true" focusable="false">${paths}</svg>`;
}

/** Status glyph OK€” replaces the OKOKOK / OKOKFAIL / OKWARNWARN characters used inline everywhere. */
function statusIcon(state) {
  if (state === true  || state === 'ok'   || state === 'up')   return icon('check', 13);
  if (state === false || state === 'fail' || state === 'down') return icon('cross', 13);
  return icon('alert', 13);
}

